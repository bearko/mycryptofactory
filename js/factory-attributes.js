/** rarity ごとの fallback 属性数 (override が無いときに使う) */
const DEFAULT_COUNT_BY_RARITY = {
  common:    1,
  uncommon:  1,
  rare:      1,
  epic:      2,
  legendary: 2,
};

/** override が無いヒーローの「とりあえず属性」を返す。
 *  passive description のキーワードでざっくり推定。
 *  失敗時は rarity の default count 分の ["shi"] を返す。 */
function inferAttributesFallback(hero) {
  const desc = (hero.passiveDesc || "").toLowerCase();
  const guesses = [];
  // クラフト系: PHY/INT 増加、攻撃力アップ系は士寄り。
  // 「治癒」「回復」 → 農、「PHY+」攻撃寄り → 士、それ以外で INT 系 → 工
  if (/(治癒|回復|hpアップ|hp\+)/.test(desc)) guesses.push("no");
  if (/(ダメージ|攻撃|phy\+|phy|出血|気絶|スタン)/.test(desc)) guesses.push("shi");
  if (/(int\+|int|魔法|魅了)/.test(desc)) guesses.push("ko");
  // 重複除去
  const uniq = [...new Set(guesses)];
  const need = DEFAULT_COUNT_BY_RARITY[hero.rarity] || 1;
  while (uniq.length < need) {
    // とりあえず 士 で埋める (保守的 default)
    if (!uniq.includes("shi")) uniq.push("shi");
    else if (!uniq.includes("sho")) uniq.push("sho");
    else if (!uniq.includes("no")) uniq.push("no");
    else uniq.push("ko");
  }
  return uniq.slice(0, need);
}

/** 1 体のヒーローに属性配列を割り当てる。
 *  ATTRIBUTE_OVERRIDES に登録があればそれを返し、無ければ inferFallback。
 */
export function inferAttributes(hero) {
  if (!hero) return ["shi"];
  const ov = ATTRIBUTE_OVERRIDES[hero.heroId];
  if (Array.isArray(ov) && ov.length > 0) return ov.slice();
  return inferAttributesFallback(hero);
}

/** ヒーローが特定属性を持っているかどうか */
export function hasAttribute(hero, attr) {
  return Array.isArray(hero?.attributes) && hero.attributes.includes(attr);
}

/** 該当属性を持っていれば 1.5 倍、持っていなければ 1.0 */
export function attributeBoostFactor(hero, attr) {
  return hasAttribute(hero, attr) ? ATTRIBUTE_BOOST : 1.0;
}

/** ゲームモード ("craft"/"quest"/"market"/"duel") に対応する属性のラベル
 *  + 1.5x boost を期待される属性キー (ko/no/sho/shi) を返す。 */
export function modeAttributeKey(mode) {
  return MODE_ATTR[mode] || null;
}
